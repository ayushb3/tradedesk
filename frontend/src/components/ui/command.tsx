/**
 * CommandDialog — a centered, portalled modal wrapping the cmdk `Command` for
 * ⌘K-style palettes. Hand-rolled overlay (portal + Escape + backdrop click),
 * matching the offline-safe approach of `ui/drawer.tsx` rather than pulling in
 * an external dialog dependency. Renders nothing when closed.
 */
interface CommandDialogProps {
  open: boolean;
  onOpenChange: (open: boolean) => void;
  children: React.ReactNode;
  /** Accessible label for the dialog region. */
  label?: string;
}

function CommandDialog({
  open,
  onOpenChange,
  children,
  label = "Command menu",
}: CommandDialogProps) {
  React.useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onOpenChange(false);
    };
    document.addEventListener("keydown", onKey);
    const prev = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      document.removeEventListener("keydown", onKey);
      document.body.style.overflow = prev;
    };
  }, [open, onOpenChange]);

  if (!open) return null;

  return createPortal(
    <div className="fixed inset-0 z-50 flex items-start justify-center p-4 pt-[12vh]">
      <div
        className="absolute inset-0 bg-black/60 backdrop-blur-sm animate-in fade-in-0"
        onClick={() => onOpenChange(false)}
        aria-hidden
      />
      <div
        role="dialog"
        aria-modal="true"
        aria-label={label}
        className="relative z-10 w-full max-w-xl overflow-hidden rounded-lg border border-border bg-popover shadow-xl animate-in fade-in-0 zoom-in-95"
      >
        <Command
          // Disable cmdk's built-in filtering — results are server-ranked.
          shouldFilter={false}
        >
          {children}
        </Command>
      </div>
    </div>,
    document.body,
  );
}

