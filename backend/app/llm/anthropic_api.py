"""AnthropicAPIProvider — LLM backend using the official `anthropic` Python SDK.

Sends trade context to the Anthropic Messages API and returns a parsed
InterviewTurn. Uses ANTHROPIC_API_KEY from .env (loaded via config.py).

Unlike ClaudeCLIProvider (which draws from the operator's OAuth subscription),
this backend uses developer pay-per-token billing. Every start_interview /
next_turn call sends a request to the Anthropic API at the rates charged
for the configured model.

# COST: model claude-opus-4 pricing (as of 2026-07-09):
#   See https://www.anthropic.com/pricing for current rates.
#   Each debrief turn = ~1 request × ~1500 input + ~300 output tokens.
#   Operators must opt in explicitly by setting TRADEDESK_LLM=api.
#
# PRIVACY: trade facts (symbol, price, P&L, tags, candle stats) are sent to
#   Anthropic's API. Credentials (API key, Webull tokens) never appear in
#   prompts — enforced by test_llm_anthropic_api.py::test_secrets_not_in_prompt_or_logs.
#   See docs/PLAN-M6-TRAINING.md §2 for the full privacy semantics.

Graceful-degradation hierarchy (all paths return a valid InterviewTurn):
  RuntimeError at __init__ → missing API key — surfaces as 501 via get_llm_provider
  anthropic.APIStatusError (401 auth, 429 rate-limit, …) → fallback to form backend
  anthropic.APIConnectionError (network) → fallback
  anthropic.APITimeoutError → fallback
  Empty content list in response → fallback
  Non-JSON text content → fallback
  JSON but wrong shape (Pydantic validation failure) → fallback

data-eng task 6.2.2.
"""
from __future__ import annotations

import json
import sys
from typing import Any

from app.config import Settings
from app.llm.base import DebriefContext
from app.llm.prompts import build_prompt_next, build_prompt_start
from app.models.training import DebriefReply, InterviewTurn

_MODEL = "claude-opus-4-8"
_MAX_TOKENS = 1024
# Generation (M8c single-shot JSON) needs more headroom than an interview turn:
# a long lesson's concepts+links payload can exceed 1024 output tokens, and a
# truncated response fails JSON parsing → the lesson is silently skipped. Used
# only by generate_json_via_api; the interview path keeps _MAX_TOKENS.
_GEN_MAX_TOKENS = 4096


class AnthropicAPIProvider:
    """LLM backend calling the Anthropic Messages API via the official SDK.

    Satisfies LLMProvider (app/llm/base.py, Protocol). On any failure the
    provider falls back to the FormProvider so the debrief always completes.

    Lazy SDK import: the `anthropic` package is only imported when this class
    is instantiated, so the module loads fine even when the SDK is not installed
    (e.g. TRADEDESK_LLM=none or TRADEDESK_LLM=claude-cli). The ImportError at
    instantiation time will surface as a 501 via base.get_llm_provider.

    Parameters
    ----------
    settings:
        App settings. Must have a non-empty `anthropic_api_key`.
    """

    name: str = "api"

    def __init__(self, settings: Settings) -> None:
        # Lazy import — only required when this backend is actually selected.
        try:
            from anthropic import Anthropic  # type: ignore[import]
        except ImportError as exc:
            raise ImportError(
                "The `anthropic` package is required for TRADEDESK_LLM=api. "
                "Install it in the primary checkout: "
                "./.venv/bin/pip install 'anthropic>=0.40.0'"
            ) from exc

        if not settings.anthropic_api_key:
            raise RuntimeError(
                "ANTHROPIC_API_KEY missing from .env — required for "
                "TRADEDESK_LLM=api. Add ANTHROPIC_API_KEY=<your-key> to .env "
                "or set the env var, then restart the server."
            )

        self._client: Any = Anthropic(api_key=settings.anthropic_api_key)
        self._model = _MODEL

    # ---------------------------------------------------------------------- #
    # LLMProvider protocol
    # ---------------------------------------------------------------------- #

    def start_interview(self, ctx: DebriefContext) -> InterviewTurn:
        """Return the setup question, generated by the Anthropic API.

        Falls back to FormProvider.start_interview on any failure.
        """
        system, user = build_prompt_start(ctx)
        turn = self._call_api(system, user)
        if turn is None:
            return self._form_start(ctx)
        return turn

    def next_turn(
        self,
        ctx: DebriefContext,
        transcript: list[dict],
        reply: DebriefReply,
    ) -> InterviewTurn:
        """Return the next interview turn, generated by the Anthropic API.

        Falls back to FormProvider.next_turn on any failure.
        """
        system, user = build_prompt_next(ctx, transcript, reply)
        turn = self._call_api(system, user)
        if turn is None:
            return self._form_next(ctx, transcript, reply)
        return turn

    # ---------------------------------------------------------------------- #
    # SDK invocation & parsing
    # ---------------------------------------------------------------------- #

    def _call_api(
        self,
        system_prompt: str,
        user_message: str,
    ) -> InterviewTurn | None:
        """Call the Anthropic Messages API and return a parsed InterviewTurn,
        or None on any failure.

        On failure, logs the failure reason to stderr (never the prompt text —
        it contains user trade data). Never logs the API key.
        """
        try:
            # COST: each call is ~1500 input + ~300 output tokens on claude-opus-4.
            # See https://www.anthropic.com/pricing for current per-token rates.
            response = self._client.messages.create(
                model=self._model,
                max_tokens=_MAX_TOKENS,
                system=system_prompt,
                messages=[{"role": "user", "content": user_message}],
            )
        except Exception as exc:
            return self._handle_api_error(exc)

        # Extract text from the first content block.
        content = getattr(response, "content", None) or []
        if not content:
            print(
                "[anthropic-api] response has empty content list — falling back",
                file=sys.stderr,
            )
            return None

        first_block = content[0]
        # SDK returns TextBlock with .type == "text" and .text attribute.
        block_type = getattr(first_block, "type", None)
        if block_type != "text":
            print(
                f"[anthropic-api] first content block type={block_type!r} "
                "(expected 'text') — falling back",
                file=sys.stderr,
            )
            return None

        assistant_text = getattr(first_block, "text", None)
        if not isinstance(assistant_text, str):
            print(
                "[anthropic-api] first content block has no .text string — falling back",
                file=sys.stderr,
            )
            return None

        return _parse_interview_turn(assistant_text, source="anthropic-api")

    def _handle_api_error(self, exc: Exception) -> None:
        """Log API errors without leaking sensitive data. Always returns None."""
        # Import here so the exception classes are only needed when this backend
        # is actually active (lazy, matching the Anthropic client import above).
        try:
            from anthropic import (  # type: ignore[import]
                APIConnectionError,
                APIStatusError,
                APITimeoutError,
            )
        except ImportError:
            # SDK was available at __init__ but somehow gone now — just log.
            print(
                f"[anthropic-api] unexpected error: {type(exc).__name__} — falling back",
                file=sys.stderr,
            )
            return None

        if isinstance(exc, APIStatusError):
            # Log status code only — never the full response body (may echo prompt).
            print(
                f"[anthropic-api] API status error {exc.status_code} — falling back",
                file=sys.stderr,
            )
        elif isinstance(exc, APIConnectionError):
            print(
                "[anthropic-api] connection error — falling back",
                file=sys.stderr,
            )
        elif isinstance(exc, APITimeoutError):
            print(
                "[anthropic-api] request timeout — falling back",
                file=sys.stderr,
            )
        else:
            print(
                f"[anthropic-api] unexpected error: {type(exc).__name__} — falling back",
                file=sys.stderr,
            )
        return None

    # ---------------------------------------------------------------------- #
    # Fallback helpers
    # ---------------------------------------------------------------------- #

    def _form_start(self, ctx: DebriefContext) -> InterviewTurn:
        """Delegate start_interview to the form backend."""
        from app.llm.form import FormProvider
        return FormProvider().start_interview(ctx)

    def _form_next(
        self,
        ctx: DebriefContext,
        transcript: list[dict],
        reply: DebriefReply,
    ) -> InterviewTurn:
        """Delegate next_turn to the form backend."""
        from app.llm.form import FormProvider
        return FormProvider().next_turn(ctx, transcript, reply)


# --------------------------------------------------------------------------- #
# Text → InterviewTurn parser (shared logic)
# --------------------------------------------------------------------------- #

def _parse_interview_turn(text: str, source: str = "anthropic-api") -> InterviewTurn | None:
    """Parse a raw text response as InterviewTurn JSON.

    Returns None on any parse or shape failure (caller will fall back).
    Logs failure reason to stderr without printing the text itself (user data).
    """
    try:
        turn_data = json.loads(text)
    except json.JSONDecodeError as exc:
        print(
            f"[{source}] InterviewTurn JSON parse error: {exc} — falling back",
            file=sys.stderr,
        )
        return None

    try:
        return InterviewTurn.model_validate(turn_data)
    except Exception as exc:
        print(
            f"[{source}] InterviewTurn shape mismatch: {exc} — falling back",
            file=sys.stderr,
        )
        return None


# --------------------------------------------------------------------------- #
# M8c — single-shot JSON generation helper (issue #54)
# --------------------------------------------------------------------------- #

def generate_json_via_api(
    system: str,
    user: str,
    settings: Settings,
) -> dict | None:
    """Single-shot JSON generation via the Anthropic Messages API.

    Self-contained sibling of the interview path — used by the M8c generation
    seam (`app.llm.generate.generate_json`). Constructs a client the same way as
    `AnthropicAPIProvider.__init__`/`_call_api`, extracts the first text block,
    and `json.loads` it into a dict. Returns None on ANY failure (missing SDK,
    missing key, API error, empty/non-text content, non-JSON, non-object) so the
    caller degrades to nothing. Never logs the API key or prompt text.
    """
    try:
        from anthropic import Anthropic  # type: ignore[import]
    except ImportError:
        print(
            "[anthropic-api] SDK not installed — cannot generate JSON",
            file=sys.stderr,
        )
        return None

    if not settings.anthropic_api_key:
        print(
            "[anthropic-api] ANTHROPIC_API_KEY missing — cannot generate JSON",
            file=sys.stderr,
        )
        return None

    try:
        client: Any = Anthropic(api_key=settings.anthropic_api_key)
        response = client.messages.create(
            model=_MODEL,
            max_tokens=_GEN_MAX_TOKENS,
            system=system,
            messages=[{"role": "user", "content": user}],
        )
    except Exception as exc:  # noqa: BLE001
        print(
            f"[anthropic-api] generate_json error: {type(exc).__name__} — returning None",
            file=sys.stderr,
        )
        return None

    content = getattr(response, "content", None) or []
    if not content:
        print("[anthropic-api] empty content list — returning None", file=sys.stderr)
        return None

    first_block = content[0]
    if getattr(first_block, "type", None) != "text":
        print(
            "[anthropic-api] first content block is not text — returning None",
            file=sys.stderr,
        )
        return None

    assistant_text = getattr(first_block, "text", None)
    if not isinstance(assistant_text, str):
        print(
            "[anthropic-api] content block has no .text string — returning None",
            file=sys.stderr,
        )
        return None

    try:
        payload = json.loads(assistant_text)
    except json.JSONDecodeError as exc:
        print(
            f"[anthropic-api] JSON parse error: {exc} — returning None",
            file=sys.stderr,
        )
        return None

    if not isinstance(payload, dict):
        print(
            f"[anthropic-api] JSON is {type(payload).__name__}, expected object — returning None",
            file=sys.stderr,
        )
        return None

    return payload
